create table if not exists public.weapon_events (
  id bigint generated by default as identity primary key,
  event_time timestamptz not null default now(),
  camera_id text not null,
  camera_location text,
  alert_type text not null default 'WEAPON',
  alert_level text,
  confidence real,
  description text,
  snapshot_url text,
  detections jsonb,
  created_at timestamptz not null default now()
);

create index if not exists weapon_events_event_time_idx on public.weapon_events (event_time desc);
create index if not exists weapon_events_camera_id_idx on public.weapon_events (camera_id);

alter table public.weapon_events enable row level security;

drop policy if exists "weapon_events_select" on public.weapon_events;
create policy "weapon_events_select" on public.weapon_events
for select
using (true);
