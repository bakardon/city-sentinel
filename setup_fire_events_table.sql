create table if not exists public.fire_events (
  id bigint generated by default as identity primary key,
  event_time timestamptz not null default now(),
  camera_id text not null,
  camera_location text,
  alert_type text not null default 'FIRE',
  alert_level text,
  confidence real,
  description text,
  snapshot_url text,
  detections jsonb,
  created_at timestamptz not null default now()
);

create index if not exists fire_events_event_time_idx on public.fire_events (event_time desc);
create index if not exists fire_events_camera_id_idx on public.fire_events (camera_id);

alter table public.fire_events enable row level security;

drop policy if exists "fire_events_select" on public.fire_events;
create policy "fire_events_select" on public.fire_events
for select
using (true);
