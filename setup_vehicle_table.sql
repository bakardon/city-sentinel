CREATE TABLE IF NOT EXISTS vehicle_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'INSIDE', -- 'INSIDE', 'EXITED', 'ALERT'
    entry_time TIMESTAMPTZ DEFAULT NOW(),
    exit_time TIMESTAMPTZ,
    entry_camera_id TEXT,
    exit_camera_id TEXT,
    alert_flag BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Create indexes for performance
CREATE INDEX IF NOT EXISTS idx_vehicle_records_plate ON vehicle_records(plate_number);
CREATE INDEX IF NOT EXISTS idx_vehicle_records_status ON vehicle_records(status);
CREATE INDEX IF NOT EXISTS idx_vehicle_records_entry_time ON vehicle_records(entry_time DESC);

