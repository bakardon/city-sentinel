create table if not exists public.violence_events (
  id bigint generated by default as identity primary key,
  event_time timestamptz not null default now(),
  camera_id text not null,
  camera_location text,
  alert_type text not null default 'VIOLENCE',
  alert_level text,
  confidence real,
  description text,
  snapshot_url text,
  detections jsonb,
  created_at timestamptz not null default now()
);

create index if not exists violence_events_event_time_idx on public.violence_events (event_time desc);
create index if not exists violence_events_camera_id_idx on public.violence_events (camera_id);

alter table public.violence_events enable row level security;

drop policy if exists "violence_events_select" on public.violence_events;
create policy "violence_events_select" on public.violence_events
for select
using (true);
