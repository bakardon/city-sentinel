create table if not exists public.knife_events (
  id bigint generated by default as identity primary key,
  event_time timestamptz not null default now(),
  camera_id text not null,
  camera_location text,
  alert_type text not null default 'KNIFE',
  alert_level text,
  confidence real,
  description text,
  snapshot_url text,
  detections jsonb,
  created_at timestamptz not null default now()
);

create index if not exists knife_events_event_time_idx on public.knife_events (event_time desc);
create index if not exists knife_events_camera_id_idx on public.knife_events (camera_id);

alter table public.knife_events enable row level security;

drop policy if exists "knife_events_select" on public.knife_events;
create policy "knife_events_select" on public.knife_events
for select
using (true);
