-- Run this SQL in your Supabase SQL Editor to create the plate_detections table
-- This table is used by the standalone plate_pipeline.py script for raw logging

CREATE TABLE IF NOT EXISTS plate_detections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plate_number TEXT NOT NULL,
    confidence FLOAT,
    camera_id TEXT,
    frame_time TIMESTAMPTZ DEFAULT NOW(),
    image_path TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Indexes for faster queries
CREATE INDEX IF NOT EXISTS idx_plate_detections_plate ON plate_detections(plate_number);
CREATE INDEX IF NOT EXISTS idx_plate_detections_time ON plate_detections(frame_time DESC);
